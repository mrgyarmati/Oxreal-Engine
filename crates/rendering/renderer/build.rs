//! Computes the source keys of the shaders this crate is built with (ADR-0019 §4).
//!
//! The renderer refuses a cooked shader directory whose keys differ: it was cooked from other
//! sources, so its shaders may not match the layouts this build packs. Computing a key hashes
//! the declared inputs of `shaders/cook.json` with the pinned Slang version from
//! `tools/slang.json`. No compiler runs, so the renderer stays in the rendering layer.
//!
//! Writes `$OUT_DIR/expected_shaders.rs`, which `src/cache.rs` includes.

#[path = "build/source_key.rs"]
mod source_key;

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() -> Result<(), String> {
    let crate_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    // This crate lives at crates/rendering/renderer, three levels below the workspace root.
    let workspace = crate_dir
        .ancestors()
        .nth(3)
        .ok_or("the crate is not inside the Oxreal workspace")?
        .to_owned();

    let slang_manifest = workspace.join("tools/slang.json");
    let recipe = crate_dir.join("shaders/cook.json");
    rerun_if_changed(&slang_manifest);
    rerun_if_changed(&recipe);

    let slang: serde_json::Value = serde_json::from_str(&read_text(&slang_manifest)?)
        .map_err(|e| format!("{}: {e}", slang_manifest.display()))?;
    let slang_version = slang["version"]
        .as_str()
        .ok_or_else(|| format!("{}: `version` must be a string", slang_manifest.display()))?;
    let shaders = source_key::parse_recipe(&read_text(&recipe)?)
        .map_err(|e| format!("{}: {e}", recipe.display()))?;

    let mut generated = String::from(
        "// Generated by build.rs from shaders/cook.json and tools/slang.json. Do not edit.\n\
         pub(crate) const EXPECTED_SHADERS: &[ExpectedShader] = &[\n",
    );
    for shader in &shaders {
        let mut contents = Vec::with_capacity(shader.inputs.len());
        for input in &shader.inputs {
            let path = workspace.join(input);
            rerun_if_changed(&path);
            // A missing input fails the build: an empty key would match nothing, silently.
            contents.push(std::fs::read(&path).map_err(|e| {
                format!(
                    "{}: declared input `{input}` can't be read ({e})",
                    recipe.display()
                )
            })?);
        }
        let key = source_key::hex(&source_key::source_key(slang_version, shader, &contents));
        let _ = writeln!(
            generated,
            "    ExpectedShader {{ name: {:?}, source_key: {:?}, entry_points: &{:?} }},",
            shader.output, key, shader.entry_points
        );
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").map_err(|e| format!("OUT_DIR: {e}"))?)
        .join("expected_shaders.rs");
    std::fs::write(&out, generated).map_err(|e| format!("writing {}: {e}", out.display()))
}

fn read_text(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("reading {}: {e}", path.display()))
}

/// Rebuilds when `path` changes. Paths outside the package are allowed; once any are given,
/// cargo stops rescanning the package by default, so every input is listed.
fn rerun_if_changed(path: &Path) {
    println!("cargo::rerun-if-changed={}", path.display());
}
